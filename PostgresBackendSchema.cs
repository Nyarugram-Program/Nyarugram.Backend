using Npgsql;

namespace Botgram.Backend.Storage;

public static class PostgresBackendSchema
{
    // Explicit offline operation, never run by constructing a repository or handling a request.
    public static async Task ApplyAsync(NpgsqlDataSource source, CancellationToken token = default)
    {
        await new PostgresMessageAcceptance(source).InitializeAsync(token);
        await using var connection = await source.OpenConnectionAsync(token);
        await using var transaction = await connection.BeginTransactionAsync(token);
        await using var command = new NpgsqlCommand("""
            SET LOCAL synchronous_commit=on;
            SELECT pg_advisory_xact_lock(7459241304232);
            CREATE SCHEMA IF NOT EXISTS botgram_backend_v1;
            CREATE TABLE IF NOT EXISTS botgram_backend_v1.schema_versions (
                version integer PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT clock_timestamp());
            CREATE TABLE IF NOT EXISTS botgram_backend_v1.accounts (
                id text PRIMARY KEY REFERENCES botgram_intake_v1.users,
                username text NOT NULL CONSTRAINT backend_accounts_username_key UNIQUE,
                display_name text NOT NULL, salt text NOT NULL, password_hash text NOT NULL,
                gid text NOT NULL CONSTRAINT backend_accounts_gid_key UNIQUE
                    CHECK (gid ~ '^[0-9]{11}$' AND substring(gid FROM 4) <> '00000000'),
                ordinal bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE);
            CREATE SEQUENCE IF NOT EXISTS botgram_backend_v1.telegram_identity START WITH 100000;
            CREATE TABLE IF NOT EXISTS botgram_backend_v1.identities (
                key text PRIMARY KEY, value bigint NOT NULL UNIQUE CHECK (value > 0),
                CHECK (key LIKE 'user:%' OR key LIKE 'chat:%'));
            CREATE TABLE IF NOT EXISTS botgram_backend_v1.contacts (
                owner_id text NOT NULL REFERENCES botgram_backend_v1.accounts,
                user_id text NOT NULL REFERENCES botgram_backend_v1.accounts,
                first_name text NOT NULL, last_name text NOT NULL,
                ordinal bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
                PRIMARY KEY(owner_id,user_id), CHECK(owner_id<>user_id));
            CREATE INDEX IF NOT EXISTS backend_contacts_reverse ON botgram_backend_v1.contacts(user_id,owner_id);
            CREATE INDEX IF NOT EXISTS backend_session_owner ON botgram_intake_v1.sessions(user_id);
            INSERT INTO botgram_backend_v1.schema_versions(version) VALUES(1) ON CONFLICT DO NOTHING;
            DO $migration$ BEGIN
            IF NOT EXISTS(SELECT 1 FROM botgram_backend_v1.schema_versions WHERE version=2) THEN
                ALTER TABLE botgram_intake_v1.events ALTER COLUMN message_id DROP NOT NULL;
                ALTER TABLE botgram_intake_v1.events DROP CONSTRAINT events_type_check;
                ALTER TABLE botgram_intake_v1.events ADD CONSTRAINT backend_event_shape CHECK (
                    (type='message.created' AND message_id IS NOT NULL)
                    OR (type IN ('conversation.created','receipt.updated','call.updated','call.signal','user.gid_changed')
                        AND message_id IS NULL AND payload IS NOT NULL));
                ALTER TABLE botgram_intake_v1.event_recipients ALTER COLUMN pts DROP NOT NULL;
                ALTER TABLE botgram_intake_v1.members ADD COLUMN position integer CHECK(position>=0);
                CREATE UNIQUE INDEX backend_member_position ON botgram_intake_v1.members(conversation_id,position);
                ALTER TABLE botgram_intake_v1.outbox ALTER COLUMN projection_version DROP NOT NULL;
                ALTER TABLE botgram_intake_v1.outbox DROP CONSTRAINT outbox_partition_key_fkey;
                CREATE TABLE botgram_backend_v1.conversations (
                    id text PRIMARY KEY REFERENCES botgram_intake_v1.conversations,
                    kind text NOT NULL CHECK(kind IN ('direct','saved','group')), title text NOT NULL,
                    created_at timestamptz NOT NULL, direct_key text UNIQUE,
                    ordinal bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE);
                CREATE TABLE botgram_backend_v1.receipts (
                    conversation_id text NOT NULL REFERENCES botgram_intake_v1.conversations,
                    user_id text NOT NULL REFERENCES botgram_intake_v1.users,
                    message_id bigint NOT NULL REFERENCES botgram_intake_v1.messages,
                    PRIMARY KEY(conversation_id,user_id));
                CREATE TABLE botgram_backend_v1.calls (
                    id text PRIMARY KEY, conversation_id text NOT NULL REFERENCES botgram_intake_v1.conversations,
                    caller_id text NOT NULL REFERENCES botgram_intake_v1.users,
                    callee_id text NOT NULL REFERENCES botgram_intake_v1.users,
                    state text NOT NULL CHECK(state IN ('ringing','active','ended','rejected')),
                    updated_at timestamptz NOT NULL,
                    ordinal bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE);
                INSERT INTO botgram_backend_v1.schema_versions(version) VALUES(2);
            END IF;
            END $migration$;
            DO $migration$ BEGIN
            IF NOT EXISTS(SELECT 1 FROM botgram_backend_v1.schema_versions WHERE version=3) THEN
                ALTER TABLE botgram_backend_v1.accounts ADD COLUMN premium boolean NOT NULL DEFAULT false;
                INSERT INTO botgram_backend_v1.schema_versions(version) VALUES(3);
            END IF;
            END $migration$;
            DO $migration$ BEGIN
            IF NOT EXISTS(SELECT 1 FROM botgram_backend_v1.schema_versions WHERE version=4) THEN
                CREATE TABLE botgram_backend_v1.wallpaper_accounts (
                    user_id text PRIMARY KEY REFERENCES botgram_backend_v1.accounts,
                    revision bigint NOT NULL DEFAULT 0 CHECK(revision>=0), installed jsonb);
                CREATE TABLE botgram_backend_v1.wallpaper_saved (
                    user_id text NOT NULL REFERENCES botgram_backend_v1.accounts,
                    key text NOT NULL, definition jsonb NOT NULL,
                    ordinal bigint GENERATED ALWAYS AS IDENTITY,
                    PRIMARY KEY(user_id,key));
                CREATE TABLE botgram_backend_v1.wallpaper_shared (
                    conversation_id text PRIMARY KEY REFERENCES botgram_backend_v1.conversations,
                    definition jsonb);
                CREATE TABLE botgram_backend_v1.wallpaper_overrides (
                    conversation_id text NOT NULL REFERENCES botgram_backend_v1.conversations,
                    user_id text NOT NULL REFERENCES botgram_backend_v1.accounts,
                    definition jsonb,
                    PRIMARY KEY(conversation_id,user_id),
                    FOREIGN KEY(conversation_id,user_id) REFERENCES botgram_intake_v1.members);
                ALTER TABLE botgram_intake_v1.events DROP CONSTRAINT events_schema_version_check;
                ALTER TABLE botgram_intake_v1.outbox DROP CONSTRAINT outbox_schema_version_check;
                ALTER TABLE botgram_intake_v1.events DROP CONSTRAINT backend_event_shape;
                ALTER TABLE botgram_intake_v1.events ADD CONSTRAINT backend_event_shape CHECK (
                    (schema_version=1 AND (
                        (type='message.created' AND message_id IS NOT NULL)
                        OR (type IN ('conversation.created','receipt.updated','call.updated','call.signal','user.gid_changed')
                            AND message_id IS NULL AND payload IS NOT NULL)))
                    OR (schema_version=2 AND type='wallpaper.changed' AND message_id IS NULL AND payload IS NOT NULL));
                ALTER TABLE botgram_intake_v1.outbox ADD CONSTRAINT backend_outbox_schema CHECK (
                    schema_version=1 OR (schema_version=2 AND projection_version IS NULL));
                INSERT INTO botgram_backend_v1.schema_versions(version) VALUES(4);
            END IF;
            END $migration$;
            DO $migration$ BEGIN
            IF NOT EXISTS(SELECT 1 FROM botgram_backend_v1.schema_versions WHERE version=5) THEN
                CREATE TABLE botgram_backend_v1.privacy_accounts (
                    user_id text PRIMARY KEY REFERENCES botgram_backend_v1.accounts,
                    state jsonb NOT NULL DEFAULT '{}'::jsonb);
                INSERT INTO botgram_backend_v1.schema_versions(version) VALUES(5);
            END IF;
            END $migration$;
            """, connection, transaction);
        await command.ExecuteNonQueryAsync(token);
        await transaction.CommitAsync(token);
    }
}
